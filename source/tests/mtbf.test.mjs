import assert from 'node:assert/strict';
import {assetMTBF,exposureError} from '../.sites-runtime/tests/mtbf.mjs';
import {seed} from '../.sites-runtime/tests/domain.mjs';
import {validateRecord} from '../.sites-runtime/tests/validation.mjs';
const d=seed(),a={...d.assets[0],exposure:{start:'2025-01-01',end:'2025-12-31',hours:8000,verified:true,source:'Test log'}};
const f={...d.incidents[0],id:'failure',date:'2025-03-01T08:00',stage:'F',impact:'F1',activity:'Corrective',status:'Approved',failureEvent:true};
const i={...f,id:'impact',date:'2025-04-01T08:00',stage:'I',parentId:f.id};
assert.equal(assetMTBF(a,[f,i,f]).hours,8000);
assert.equal(assetMTBF(a,[f,{...f,id:'second',date:'2025-09-01T08:00'}]).hours,4000);
assert.equal(assetMTBF(a,[{...f,status:'Draft'}]).hours,null);
assert.equal(assetMTBF(a,[{...f,date:'2024-12-31T08:00'}, {...i,parentId:'failure'}]).failures,0);
assert.equal(assetMTBF({...a,exposure:{...a.exposure,verified:false}},[f]).hours,null);
assert.equal(assetMTBF(a,[]).hours,null);
assert.ok(exposureError({...a.exposure,hours:9000},a.commissioned));
assert.ok(exposureError({...a.exposure,end:'2024-01-01'},a.commissioned));
const data={...d,incidents:[f]};
assert.equal(validateRecord('incidents',{...i,status:'Draft'},data),null);
assert.ok(validateRecord('incidents',{...i,status:'Draft',stage:'D'},data));
assert.ok(validateRecord('incidents',{...i,status:'Draft',assetId:d.assets[1].id},data));
assert.ok(d.assets.every(a=>assetMTBF(a,d.incidents).hours>0));
console.log('MTBF: 12 exposure, deduplication, lifecycle and validation checks passed.');
