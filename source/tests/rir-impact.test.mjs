import assert from 'node:assert/strict';
import {seed,dcbf,defaultAssumptions,modelEvidence} from '../.sites-runtime/tests/domain.mjs';
const d=seed(),p={...defaultAssumptions,evidenceMode:'Reviewed',year:2026,evidenceThrough:'2026-09-28'};
const base=dcbf(d,'AST-1',p);
const rir={...d.incidents.find(e=>e.assetId==='AST-1'&&e.impact==='F1'),id:'new-2026',date:'2026-09-28T12:00',status:'Draft',stage:'F',failureEvent:true,loss:25000000,downtime:15,maintenance:300000};
const draft=dcbf({...d,incidents:[...d.incidents,rir]},'AST-1',p);
assert.deepEqual(base.timing,draft.timing);
const approved={...rir,status:'Approved'};
const live={...d,incidents:[...d.incidents,approved]};const updated=dcbf(live,'AST-1',p);
assert.equal(updated.ev.rows.length,base.ev.rows.length+1);
assert.notEqual(updated.ev.crow.beta,base.ev.crow.beta);
assert.notEqual(updated.forecasts[0].failures,base.forecasts[0].failures);
for(const k of ['npv','irr','payback','pi'])assert.notEqual(updated.scenarios[1][k],base.scenarios[1][k]);
assert.deepEqual(dcbf({...d,incidents:[...d.incidents,{...approved,impact:'F2'}]},'AST-1',p).timing,base.timing);
assert.deepEqual(dcbf({...d,incidents:[...d.incidents,{...approved,date:'2026-09-29T00:00'}]},'AST-1',p).timing,base.timing);
const linked={...approved,id:'impact',parentId:approved.id,stage:'I',date:'2026-09-28T15:00',failureEvent:false,loss:1000000,maintenance:0,downtime:0};
const withImpact=dcbf({...live,incidents:[...live.incidents,linked]},'AST-1',p);
assert.equal(withImpact.ev.rows.length,updated.ev.rows.length);assert.ok(withImpact.avgLoss>updated.avgLoss);
assert.ok(updated.timing.slice(1).some(s=>s.irr!==null));
assert.deepEqual(dcbf(live,'AST-1',{...p,model:'Manual'}).forecasts.map(f=>f.failures),dcbf(d,'AST-1',{...p,model:'Manual'}).forecasts.map(f=>f.failures));
console.log('RIR impact: approval, current-year cutoff, forecast refit, four economic metrics, linked lifecycle and manual-model checks passed.');
